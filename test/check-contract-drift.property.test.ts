/**
 * Feature: admin-quality-gates-and-shared-contracts
 * Contract_Drift_Check (Admin_Repository side)
 *
 * Validates: Requirements 9.7, 10.4, 10.5, 10.8
 *
 * Drives the declaration-less `scripts/check-contract-drift.mjs` (loaded through a
 * computed specifier so `tsc --noEmit` stays clean — the repo tsconfig has no allowJs)
 * over:
 *   - pure helpers (`diffContractFields`, `isTransientReadError`, `parseContractVersion`)
 *     with fast-check, and
 *   - the whole `runContractDriftCheck` runner against real temporary fixture directories,
 *     with an injected clock/sleeper/readFileSync so version skew, byte drift, and the
 *     transient-unreachability retry budget are deterministic.
 */
import { describe, expect, it } from "vitest";
import fc from "fast-check";
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";

interface DriftOutcome {
  ok: boolean;
  exitCode: number;
  stdout: string[];
  stderr: string[];
}

interface ContractFields {
  contractVersion: number | string | null;
  factStatuses: string[];
  quantityKinds: string[];
  transitions: string[];
  lifecycleFields: string[];
}

interface DriftModule {
  CONTRACT_SOURCE_FILENAME: string;
  CONTRACT_ADOPTION_FILENAME: string;
  CONSUMED_ARTIFACT_RELATIVE_PATH: string;
  EXIT_DRIFT: number;
  EXIT_UNREACHABLE: number;
  EXIT_CONFIG_UNREADABLE: number;
  MAX_ATTEMPTS: number;
  isTransientReadError(error: unknown): boolean;
  parseContractVersion(source: string): number | string | null;
  extractContractFields(source: string): ContractFields;
  diffContractFields(consumed: ContractFields, published: ContractFields): string[];
  runContractDriftCheck(options?: {
    root?: string;
    readFileSync?: (p: string, enc: string) => string;
    now?: () => number;
    sleep?: (ms: number) => void;
  }): DriftOutcome;
}

const SPECIFIER = new URL("../scripts/check-contract-drift.mjs", import.meta.url).href;
const mod = (await import(/* @vite-ignore */ SPECIFIER)) as DriftModule;
const {
  CONTRACT_SOURCE_FILENAME,
  CONTRACT_ADOPTION_FILENAME,
  CONSUMED_ARTIFACT_RELATIVE_PATH,
  EXIT_DRIFT,
  EXIT_UNREACHABLE,
  EXIT_CONFIG_UNREADABLE,
  MAX_ATTEMPTS,
  isTransientReadError,
  parseContractVersion,
  extractContractFields,
  diffContractFields,
  runContractDriftCheck,
} = mod;

// A representative artifact in the shape the Contract_Generator emits.
const ARTIFACT_V1 = [
  "// Code generated by scripts/gen_shared_contract.mjs; DO NOT EDIT.",
  "",
  "export const CONTRACT_VERSION = 1;",
  "",
  'export const FACT_STATUSES = ["pending", "active", "disputed", "retired"] as const;',
  'export type FactStatus = (typeof FACT_STATUSES)[number];',
  "",
  "export const STATUS_TRANSITIONS: readonly StatusTransition[] = [",
  '  { from: "pending", to: "active", adminAuthorized: true },',
  '  { from: "retired", to: "active", adminAuthorized: false },',
  "] as const;",
  "",
  "export const QUANTITY_KINDS = [",
  '  "year",',
  '  "count",',
  "] as const;",
  "",
  "export const LIFECYCLE_FIELDS: readonly FieldDescriptor[] = [",
  '  { name: "plausible_min", type: "number", required: false },',
  "] as const;",
  "",
].join("\n");

function makeFixture(options: {
  consumed: string;
  published?: string;
  adoption: string;
  source?: string;
  writePublished?: boolean;
}): string {
  const root = mkdtempSync(path.join(os.tmpdir(), "contract-drift-"));
  const consumedAbs = path.join(root, CONSUMED_ARTIFACT_RELATIVE_PATH);
  mkdirSync(path.dirname(consumedAbs), { recursive: true });
  writeFileSync(consumedAbs, options.consumed, "utf8");

  // Published copy lives one directory up, mirroring the side-by-side checkout.
  const publishedRel = "../published-repo/shared/fact-lifecycle-contract.gen.ts";
  if (options.writePublished !== false) {
    const publishedAbs = path.resolve(root, publishedRel);
    mkdirSync(path.dirname(publishedAbs), { recursive: true });
    writeFileSync(publishedAbs, options.published ?? options.consumed, "utf8");
  }

  writeFileSync(
    path.join(root, CONTRACT_SOURCE_FILENAME),
    options.source ?? JSON.stringify({ publishedArtifactPath: publishedRel }),
    "utf8",
  );
  writeFileSync(path.join(root, CONTRACT_ADOPTION_FILENAME), options.adoption, "utf8");
  return root;
}

function withFixture(
  options: Parameters<typeof makeFixture>[0],
  body: (root: string) => void,
): void {
  const root = makeFixture(options);
  try {
    body(root);
  } finally {
    rmSync(root, { recursive: true, force: true, maxRetries: 3 });
    // The published copy sits outside `root`; clean its parent too.
    rmSync(path.resolve(root, "../published-repo"), {
      recursive: true,
      force: true,
      maxRetries: 3,
    });
  }
}

// ---------------------------------------------------------------------------
// Requirement 10.4 — byte-identical + matching version passes.
// ---------------------------------------------------------------------------

describe("Requirement 10.4: byte-identical consumed and published copies pass", () => {
  it("exits 0 with no stderr and does not modify the consumed copy", () => {
    withFixture(
      { consumed: ARTIFACT_V1, adoption: JSON.stringify({ adopted: true, contractVersion: 1 }) },
      (root) => {
        const consumedPath = path.join(root, CONSUMED_ARTIFACT_RELATIVE_PATH);
        const before = readFileSync(consumedPath);
        const outcome = runContractDriftCheck({ root });
        expect(outcome.ok).toBe(true);
        expect(outcome.exitCode).toBe(0);
        expect(outcome.stderr).toEqual([]);
        expect(readFileSync(consumedPath).equals(before)).toBe(true);
      },
    );
  });
});

// ---------------------------------------------------------------------------
// Requirements 9.7 / 10.5 — version mismatch reports both versions, exits non-zero.
// ---------------------------------------------------------------------------

describe("Requirement 9.7: a Contract_Version mismatch fails with both versions named", () => {
  it("reports recorded and published versions and exits non-zero", () => {
    const publishedV2 = ARTIFACT_V1.replace(
      "export const CONTRACT_VERSION = 1;",
      "export const CONTRACT_VERSION = 2;",
    );
    withFixture(
      {
        consumed: ARTIFACT_V1,
        published: publishedV2,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        const consumedPath = path.join(root, CONSUMED_ARTIFACT_RELATIVE_PATH);
        const before = readFileSync(consumedPath);
        const outcome = runContractDriftCheck({ root });
        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_DRIFT);
        const err = outcome.stderr.join("\n");
        expect(err).toContain("Contract_Version mismatch");
        expect(err).toContain("recorded 1");
        expect(err).toContain("published 2");
        expect(readFileSync(consumedPath).equals(before)).toBe(true);
      },
    );
  });
});

// ---------------------------------------------------------------------------
// Requirement 10.5 — byte difference reports the differing field/value names.
// ---------------------------------------------------------------------------

describe("Requirement 10.5: a byte difference names the differing fields/values", () => {
  it("names an added fact status and leaves the consumed copy unmodified", () => {
    // Same version, but the published copy adds a status → real drift by field name.
    const publishedExtra = ARTIFACT_V1.replace(
      '"retired"] as const',
      '"retired", "archived"] as const',
    );
    withFixture(
      {
        consumed: ARTIFACT_V1,
        published: publishedExtra,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        const consumedPath = path.join(root, CONSUMED_ARTIFACT_RELATIVE_PATH);
        const before = readFileSync(consumedPath);
        const outcome = runContractDriftCheck({ root });
        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_DRIFT);
        const err = outcome.stderr.join("\n");
        expect(err).toContain("differs from the published copy");
        expect(err).toContain("FACT_STATUSES");
        expect(err).toContain("archived");
        expect(readFileSync(consumedPath).equals(before)).toBe(true);
      },
    );
  });
});

// ---------------------------------------------------------------------------
// Requirement 10.8 — transient unreachability is retried then fails closed.
// ---------------------------------------------------------------------------

describe("Requirement 10.8: transient unreachability retries then fails closed", () => {
  it("retries up to MAX_ATTEMPTS on a transient error, then exits non-zero naming the reference", () => {
    withFixture(
      {
        consumed: ARTIFACT_V1,
        writePublished: false,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        const publishedAbs = path.resolve(
          root,
          "../published-repo/shared/fact-lifecycle-contract.gen.ts",
        );
        let publishedReads = 0;
        const readFileSyncStub = (p: string, enc: string): string => {
          if (path.resolve(p) === path.resolve(publishedAbs)) {
            publishedReads += 1;
            const err = new Error("resource temporarily unavailable") as Error & { code: string };
            err.code = "EBUSY";
            throw err;
          }
          return readFileSync(p, enc as BufferEncoding).toString();
        };
        let clock = 0;
        const outcome = runContractDriftCheck({
          root,
          readFileSync: readFileSyncStub,
          now: () => clock,
          sleep: (ms: number) => {
            clock += ms;
          },
        });
        expect(publishedReads).toBe(MAX_ATTEMPTS);
        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_UNREACHABLE);
        const err = outcome.stderr.join("\n");
        expect(err).toContain("unreachable");
        expect(err).toContain("attempted reference");
        expect(err).toContain("shared/fact-lifecycle-contract.gen.ts");
      },
    );
  });

  it("does not retry a missing published copy (ENOENT is not transient) and fails closed", () => {
    withFixture(
      {
        consumed: ARTIFACT_V1,
        writePublished: false,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        const outcome = runContractDriftCheck({ root });
        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_UNREACHABLE);
        expect(outcome.stderr.join("\n")).toContain("unreachable");
      },
    );
  });
});

