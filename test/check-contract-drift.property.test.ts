// ---------------------------------------------------------------------------
// Pure helpers under fast-check.
// ---------------------------------------------------------------------------

describe("isTransientReadError: retry codes are transient, ENOENT is not", () => {
  it("treats known transient codes as transient and ENOENT/others as non-transient", () => {
    fc.assert(
      fc.property(
        fc.constantFrom("EBUSY", "EAGAIN", "EMFILE", "ETIMEDOUT", "EACCES"),
        (code) => {
          expect(isTransientReadError({ code })).toBe(true);
        },
      ),
    );
    expect(isTransientReadError({ code: "ENOENT" })).toBe(false);
    expect(isTransientReadError(new Error("no code"))).toBe(false);
  });
});

describe("diffContractFields: identical fields diff empty; a changed field is named", () => {
  it("returns no differences for identical extractions and names any changed group", () => {
    const base = extractContractFields(ARTIFACT_V1);
    expect(diffContractFields(base, base)).toEqual([]);

    fc.assert(
      fc.property(fc.constantFrom("frobnicated", "archived", "sealed"), (extraStatus) => {
        const changed = extractContractFields(
          ARTIFACT_V1.replace('"retired"] as const', `"retired", "${extraStatus}"] as const`),
        );
        const diffs = diffContractFields(base, changed);
        expect(diffs.some((d) => d.includes("FACT_STATUSES") && d.includes(extraStatus))).toBe(true);
      }),
    );
  });
});

describe("parseContractVersion: reads integer and string CONTRACT_VERSION, null when absent", () => {
  it("parses an integer, a quoted string, and returns null when the declaration is absent", () => {
    expect(parseContractVersion("export const CONTRACT_VERSION = 7;")).toBe(7);
    expect(parseContractVersion('export const CONTRACT_VERSION = "1.2.0";')).toBe("1.2.0");
    expect(parseContractVersion("no version here")).toBe(null);
  });
});
