/**
 * Feature: admin-quality-gates-and-shared-contracts
 * Contract_Drift_Check (Admin_Repository side) — example tests (task 11.5).
 *
 * Validates: Requirements 9.7, 10.5, 10.8, 10.10
 *
 * These are worked examples that complement the generated properties in
 * `check-contract-drift.property.test.ts` (task 11.2). That file already covers
 * the byte-identical pass (10.4), a version mismatch reporting both versions
 * (9.7), a fact-status byte diff naming the differing field (10.5), the
 * transient retry-then-fail-closed path and the ENOENT non-retry path (10.8),
 * fail-closed configuration, and the pure helpers. This file deliberately does
 * NOT repeat those; it pins the angles that file leaves open:
 *
 *   - Requirement 10.10 — POST-SYNC CLEARING. After a drift is resolved by making
 *     the consumed copy byte-identical to the published copy AND recording the
 *     matching Contract_Version, `runContractDriftCheck` exits 0 so Quality_Gate
 *     passes. This is the requirement the property file does not touch at all.
 *   - Requirement 9.7 — the version mismatch is reported WITHIN 5 SECONDS. Asserted
 *     deterministically against an injected clock rather than left implicit.
 *   - Requirement 10.8 — after exactly 3 transient attempts the ATTEMPTED REFERENCE
 *     is reported, and the whole retry sequence stays inside the 60 s budget,
 *     asserted against an injected clock.
 *   - Requirement 10.5 — a byte diff also names non-fact-status groups
 *     (STATUS_TRANSITIONS, QUANTITY_KINDS), a reporting angle the property file's
 *     single fact-status example does not exercise.
 *
 * The runner is driven over real temporary fixture directories with injected
 * `readFileSync`, `now`, and `sleep` seams so every assertion is offline and
 * deterministic. Every temporary directory is removed after the test that
 * created it.
 */
import { describe, expect, it } from "vitest";
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";

interface DriftOutcome {
  ok: boolean;
  exitCode: number;
  stdout: string[];
  stderr: string[];
}

interface DriftModule {
  CONTRACT_SOURCE_FILENAME: string;
  CONTRACT_ADOPTION_FILENAME: string;
  CONSUMED_ARTIFACT_RELATIVE_PATH: string;
  EXIT_DRIFT: number;
  EXIT_UNREACHABLE: number;
  EXIT_CONFIG_UNREADABLE: number;
  MAX_ATTEMPTS: number;
  TOTAL_RETRY_BUDGET_MS: number;
  runContractDriftCheck(options?: {
    root?: string;
    readFileSync?: (p: string, enc: string) => string;
    now?: () => number;
    sleep?: (ms: number) => void;
  }): DriftOutcome;
}

// Loaded through a computed specifier: the `.mjs` script has no type
// declarations and the repo tsconfig has no allowJs, so a static import would
// not typecheck under `strict`.
const SPECIFIER = new URL("../scripts/check-contract-drift.mjs", import.meta.url).href;
const mod = (await import(/* @vite-ignore */ SPECIFIER)) as DriftModule;
const {
  CONTRACT_SOURCE_FILENAME,
  CONTRACT_ADOPTION_FILENAME,
  CONSUMED_ARTIFACT_RELATIVE_PATH,
  EXIT_DRIFT,
  EXIT_UNREACHABLE,
  MAX_ATTEMPTS,
  TOTAL_RETRY_BUDGET_MS,
  runContractDriftCheck,
} = mod;

/** A representative artifact in the shape the Contract_Generator emits, at version 1. */
const ARTIFACT_V1 = [
  "// Code generated by scripts/gen_shared_contract.mjs; DO NOT EDIT.",
  "",
  "export const CONTRACT_VERSION = 1;",
  "",
  'export const FACT_STATUSES = ["pending", "active", "disputed", "retired"] as const;',
  "export type FactStatus = (typeof FACT_STATUSES)[number];",
  "",
  "export const STATUS_TRANSITIONS: readonly StatusTransition[] = [",
  '  { from: "pending", to: "active", adminAuthorized: true },',
  '  { from: "retired", to: "active", adminAuthorized: false },',
  "] as const;",
  "",
  "export const QUANTITY_KINDS = [",
  '  "year",',
  '  "count",',
  "] as const;",
  "",
  "export const LIFECYCLE_FIELDS: readonly FieldDescriptor[] = [",
  '  { name: "plausible_min", type: "number", required: false },',
  "] as const;",
  "",
].join("\n");

/**
 * The published copy is kept INSIDE this file's own fixture root, under a
 * dedicated `published-repo/` subdirectory. Keeping it self-contained (rather
 * than one directory up in the shared OS temp root) means these fixtures never
 * collide with the sibling drift test files that place their published copy at
 * `../published-repo`; those files and this one run in parallel Vitest workers
 * against the same `os.tmpdir()`, so a shared relative path would let one
 * worker's cleanup delete another's published copy mid-read. The tracked
 * `publishedArtifactPath` is a repo-relative reference either way, so a nested
 * location exercises the same resolution path (Requirement 10.4).
 */
const PUBLISHED_REL = "published-repo/shared/fact-lifecycle-contract.gen.ts";

function publishedAbsFor(root: string): string {
  return path.resolve(root, PUBLISHED_REL);
}

function makeFixture(options: {
  consumed: string;
  published?: string;
  adoption: string;
  writePublished?: boolean;
}): string {
  const root = mkdtempSync(path.join(os.tmpdir(), "contract-drift-clearing-"));

  const consumedAbs = path.join(root, CONSUMED_ARTIFACT_RELATIVE_PATH);
  mkdirSync(path.dirname(consumedAbs), { recursive: true });
  writeFileSync(consumedAbs, options.consumed, "utf8");

  if (options.writePublished !== false) {
    const publishedAbs = publishedAbsFor(root);
    mkdirSync(path.dirname(publishedAbs), { recursive: true });
    writeFileSync(publishedAbs, options.published ?? options.consumed, "utf8");
  }

  writeFileSync(
    path.join(root, CONTRACT_SOURCE_FILENAME),
    JSON.stringify({ publishedArtifactPath: PUBLISHED_REL }),
    "utf8",
  );
  writeFileSync(path.join(root, CONTRACT_ADOPTION_FILENAME), options.adoption, "utf8");
  return root;
}

function withFixture(
  options: Parameters<typeof makeFixture>[0],
  body: (root: string) => void,
): void {
  const root = makeFixture(options);
  try {
    body(root);
  } finally {
    // The published copy is nested inside `root`, so a single recursive removal
    // takes the whole fixture — including nothing outside this file's own tree.
    rmSync(root, { recursive: true, force: true, maxRetries: 3 });
  }
}

function consumedPathFor(root: string): string {
  return path.join(root, CONSUMED_ARTIFACT_RELATIVE_PATH);
}

/** Overwrites the consumed copy in place, as a real post-sync update would. */
function rewriteConsumed(root: string, contents: string): void {
  writeFileSync(consumedPathFor(root), contents, "utf8");
}

/** Overwrites the recorded adoption/version file in place. */
function rewriteAdoption(root: string, adoption: string): void {
  writeFileSync(path.join(root, CONTRACT_ADOPTION_FILENAME), adoption, "utf8");
}

// ---------------------------------------------------------------------------
// Requirement 10.10 — post-sync clearing: byte-identical + matching version → 0
// ---------------------------------------------------------------------------

describe("Requirement 10.10: syncing the consumed copy and version clears the drift", () => {
  it("exits 0 once a byte drift is resolved by copying the published bytes and matching the version", () => {
    // Start from a real drift the property file's report path recognises: the
    // published copy is at version 2 with an extra status, the consumed copy is
    // the stale version-1 artifact.
    const publishedV2 = ARTIFACT_V1.replace(
      "export const CONTRACT_VERSION = 1;",
      "export const CONTRACT_VERSION = 2;",
    ).replace('"retired"] as const', '"retired", "archived"] as const');

    withFixture(
      {
        consumed: ARTIFACT_V1,
        published: publishedV2,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        // Before the sync: drift is detected and the gate would fail.
        const before = runContractDriftCheck({ root });
        expect(before.ok).toBe(false);
        expect(before.exitCode).toBe(EXIT_DRIFT);

        // Perform the sync exactly as the requirement describes: make the consumed
        // copy byte-identical to the published copy AND record the matching version.
        rewriteConsumed(root, publishedV2);
        rewriteAdoption(root, JSON.stringify({ adopted: true, contractVersion: 2 }));

        // After the sync: the check passes so Quality_Gate proceeds.
        const after = runContractDriftCheck({ root });
        expect(after.ok).toBe(true);
        expect(after.exitCode).toBe(0);
        expect(after.stderr).toEqual([]);
        expect(after.stdout.join("\n")).toContain("byte-identical");
      },
    );
  });

  it("exits 0 after a version-only skew is cleared by recording the published version", () => {
    // A pure version skew: the bytes already match the published copy, but the
    // recorded version lags. This is the case Requirement 10.9 leaves the admin
    // gate failing; recording the matching version clears it (Requirement 10.10).
    const publishedV3 = ARTIFACT_V1.replace(
      "export const CONTRACT_VERSION = 1;",
      "export const CONTRACT_VERSION = 3;",
    );

    withFixture(
      {
        consumed: publishedV3, // bytes already synced
        published: publishedV3,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }), // version lags
      },
      (root) => {
        const before = runContractDriftCheck({ root });
        expect(before.ok).toBe(false);
        expect(before.exitCode).toBe(EXIT_DRIFT);
        expect(before.stderr.join("\n")).toContain("Contract_Version mismatch");

        // Record the matching version; bytes are already identical.
        rewriteAdoption(root, JSON.stringify({ adopted: true, contractVersion: 3 }));

        const after = runContractDriftCheck({ root });
        expect(after.ok).toBe(true);
        expect(after.exitCode).toBe(0);
        expect(after.stderr).toEqual([]);
      },
    );
  });

  it("still fails if the version is synced but the bytes are not, then clears when both match", () => {
    // Guards against a false "cleared" reading: matching the version alone is not
    // enough while the bytes still differ. The gate only clears when BOTH agree.
    const publishedV2 = ARTIFACT_V1.replace(
      "export const CONTRACT_VERSION = 1;",
      "export const CONTRACT_VERSION = 2;",
    ).replace('"count",', '"count",\n  "distance",');

    withFixture(
      {
        consumed: ARTIFACT_V1,
        published: publishedV2,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        // Match only the recorded version — bytes still differ.
        rewriteAdoption(root, JSON.stringify({ adopted: true, contractVersion: 2 }));
        const halfSynced = runContractDriftCheck({ root });
        expect(halfSynced.ok).toBe(false);
        expect(halfSynced.exitCode).toBe(EXIT_DRIFT);
        expect(halfSynced.stderr.join("\n")).toContain("differs from the published copy");

        // Now also sync the bytes: the drift clears.
        rewriteConsumed(root, publishedV2);
        const fullySynced = runContractDriftCheck({ root });
        expect(fullySynced.ok).toBe(true);
        expect(fullySynced.exitCode).toBe(0);
        expect(fullySynced.stderr).toEqual([]);
      },
    );
  });
});

// ---------------------------------------------------------------------------
// Requirement 9.7 — a version mismatch is reported within 5 seconds
// ---------------------------------------------------------------------------

describe("Requirement 9.7: a Contract_Version mismatch is reported within 5 seconds", () => {
  it("reports both versions and consumes less than 5 s of the injected clock", () => {
    const publishedV2 = ARTIFACT_V1.replace(
      "export const CONTRACT_VERSION = 1;",
      "export const CONTRACT_VERSION = 2;",
    );

    withFixture(
      {
        consumed: ARTIFACT_V1,
        published: publishedV2,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        // A monotonic injected clock that advances 1 ms per read. Any retry-style
        // waiting would advance it materially; the version-mismatch path should
        // short-circuit long before the 5 000 ms bound.
        let clock = 0;
        const now = (): number => {
          clock += 1;
          return clock;
        };
        const startedAt = clock;

        const outcome = runContractDriftCheck({
          root,
          now,
          // If the runner ever slept on this path it would blow the budget; make a
          // sleep advance the clock so the assertion below would catch it.
          sleep: (ms: number) => {
            clock += ms;
          },
        });

        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_DRIFT);
        const err = outcome.stderr.join("\n");
        expect(err).toContain("Contract_Version mismatch");
        expect(err).toContain("recorded 1");
        expect(err).toContain("published 2");

        // Within 5 s on the injected clock (Requirement 9.7). The mismatch path
        // takes no retry backoff, so the elapsed budget is a tiny handful of ms.
        const elapsed = clock - startedAt;
        expect(elapsed).toBeLessThan(5_000);
      },
    );
  });
});

// ---------------------------------------------------------------------------
// Requirement 10.8 — after 3 retries the attempted reference is reported, in budget
// ---------------------------------------------------------------------------

describe("Requirement 10.8: after the 3-attempt retry budget the attempted reference is reported", () => {
  it("makes exactly MAX_ATTEMPTS transient reads, names the attempted reference, and stays inside 60 s", () => {
    withFixture(
      {
        consumed: ARTIFACT_V1,
        writePublished: false,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        const publishedAbs = publishedAbsFor(root);
        let publishedReads = 0;
        const readFileSyncStub = (p: string, enc: string): string => {
          if (path.resolve(p) === path.resolve(publishedAbs)) {
            publishedReads += 1;
            const err = new Error("resource temporarily unavailable") as Error & {
              code: string;
            };
            err.code = "EAGAIN"; // transient → retried
            throw err;
          }
          return readFileSync(p, enc as BufferEncoding).toString();
        };

        let clock = 0;
        const startedAt = clock;
        const outcome = runContractDriftCheck({
          root,
          readFileSync: readFileSyncStub,
          now: () => clock,
          sleep: (ms: number) => {
            clock += ms;
          },
        });

        // Retried up to the full budget, then failed closed.
        expect(publishedReads).toBe(MAX_ATTEMPTS);
        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_UNREACHABLE);

        const err = outcome.stderr.join("\n");
        expect(err).toContain("unreachable");
        expect(err).toContain(`${MAX_ATTEMPTS} attempts`);
        // The attempted reference (the tracked repo-relative path) is named so an
        // operator knows exactly what could not be resolved.
        expect(err).toContain("attempted reference");
        expect(err).toContain("shared/fact-lifecycle-contract.gen.ts");
        expect(err).toContain("failing closed");

        // The retry sequence stays well within the 60 s total budget (Requirement 10.8).
        const elapsed = clock - startedAt;
        expect(elapsed).toBeLessThan(TOTAL_RETRY_BUDGET_MS);
      },
    );
  });
});

// ---------------------------------------------------------------------------
// Requirement 10.5 — a byte diff also names transition and quantity-kind groups
// ---------------------------------------------------------------------------

describe("Requirement 10.5: a byte diff names non-fact-status groups too", () => {
  it("names an added STATUS_TRANSITIONS tuple and leaves the consumed copy unmodified", () => {
    // Same version, but the published copy adds an admin-authorized transition.
    const publishedExtraTransition = ARTIFACT_V1.replace(
      '  { from: "retired", to: "active", adminAuthorized: false },',
      [
        '  { from: "retired", to: "active", adminAuthorized: false },',
        '  { from: "active", to: "disputed", adminAuthorized: true },',
      ].join("\n"),
    );

    withFixture(
      {
        consumed: ARTIFACT_V1,
        published: publishedExtraTransition,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        const consumedPath = consumedPathFor(root);
        const before = readFileSync(consumedPath);

        const outcome = runContractDriftCheck({ root });

        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_DRIFT);
        const err = outcome.stderr.join("\n");
        expect(err).toContain("differs from the published copy");
        expect(err).toContain("STATUS_TRANSITIONS");
        expect(err).toContain("active->disputed:true");
        // Consumed copy is never rewritten by the check.
        expect(readFileSync(consumedPath).equals(before)).toBe(true);
      },
    );
  });

  it("names an added QUANTITY_KINDS value", () => {
    const publishedExtraKind = ARTIFACT_V1.replace(
      '  "count",',
      '  "count",\n  "distance",',
    );

    withFixture(
      {
        consumed: ARTIFACT_V1,
        published: publishedExtraKind,
        adoption: JSON.stringify({ adopted: true, contractVersion: 1 }),
      },
      (root) => {
        const outcome = runContractDriftCheck({ root });
        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_DRIFT);
        const err = outcome.stderr.join("\n");
        expect(err).toContain("QUANTITY_KINDS");
        expect(err).toContain("distance");
      },
    );
  });
});
