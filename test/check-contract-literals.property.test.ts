/**
 * Feature: admin-quality-gates-and-shared-contracts
 * Property 31: No fact-status or quantity-kind literal appears outside the artifact
 *
 * *For all* TypeScript source files in Admin_Repository other than the
 * Shared_Contract_Artifact, no fact-status string literal and no `quantity_kind`
 * string literal appears; when one does, the Quality_Gate scan reports the file
 * path and offending literal on standard error and exits non-zero.
 *
 * Validates: Requirements 9.9
 *
 * The property is driven over the pure per-file scanner (`scanSourceForLiterals`)
 * and the forbidden-set parser (`parseForbiddenLiterals`) with fast-check, plus a
 * handful of real temporary fixture directories that exercise the whole runner
 * end to end (deriving the forbidden set from a real artifact file, walking a
 * real `src/` tree, and reporting `path:line: literal`). The forbidden set is
 * always derived from the artifact, never hardcoded, so a status or quantity kind
 * added to the artifact is forbidden automatically.
 */
import { describe, expect, it } from "vitest";
import fc from "fast-check";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

// ---------------------------------------------------------------------------
// Module under test — a declaration-less `.mjs` loaded through a computed
// specifier so `tsc --noEmit` stays clean (the repo tsconfig has no allowJs).
// ---------------------------------------------------------------------------

interface LiteralCheckOutcome {
  ok: boolean;
  exitCode: number;
  stdout: string[];
  stderr: string[];
}

interface ContractLiteralModule {
  ARTIFACT_RELATIVE_PATH: string;
  EXIT_LITERAL_FOUND: number;
  EXIT_ARTIFACT_UNREADABLE: number;
  parseForbiddenLiterals(artifactSource: string): {
    values: Set<string>;
    statuses: string[];
    quantityKinds: string[];
  };
  parseStringArrayConst(source: string, constName: string): string[];
  scanSourceForLiterals(
    source: string,
    forbidden: Set<string>,
  ): { line: number; index: number; literal: string }[];
  listScannedFiles(
    root: string,
    options?: { scanDir?: string; artifactPath?: string },
  ): string[];
  runContractLiteralCheck(
    root?: string,
    options?: { scanDir?: string; artifactPath?: string },
  ): LiteralCheckOutcome;
}

const SPECIFIER = new URL("../scripts/check-contract-literals.mjs", import.meta.url).href;
const mod = (await import(/* @vite-ignore */ SPECIFIER)) as ContractLiteralModule;
const {
  parseForbiddenLiterals,
  scanSourceForLiterals,
  runContractLiteralCheck,
  ARTIFACT_RELATIVE_PATH,
  EXIT_LITERAL_FOUND,
  EXIT_ARTIFACT_UNREADABLE,
} = mod;

// A representative artifact in the shape the Contract_Generator emits.
const ARTIFACT_SOURCE = [
  "// Code generated by scripts/gen_shared_contract.mjs; DO NOT EDIT.",
  'export const CONTRACT_VERSION = 1;',
  'export const FACT_STATUSES = ["pending", "active", "disputed", "retired"] as const;',
  "export const QUANTITY_KINDS = [",
  '  "year",',
  '  "count",',
  '  "percentage",',
  '  "ratio",',
  '  "physical_measure",',
  '  "money",',
  '  "duration",',
  '  "rating",',
  "] as const;",
  "",
].join("\n");

const forbidden = parseForbiddenLiterals(ARTIFACT_SOURCE);
const FORBIDDEN_VALUES = [...forbidden.values];

// ---------------------------------------------------------------------------
// Fixture plumbing
// ---------------------------------------------------------------------------

function makeFixture(files: Record<string, string>, artifact = ARTIFACT_SOURCE): string {
  const root = mkdtempSync(path.join(os.tmpdir(), "contract-literals-"));
  const artifactAbs = path.join(root, ARTIFACT_RELATIVE_PATH);
  mkdirSync(path.dirname(artifactAbs), { recursive: true });
  writeFileSync(artifactAbs, artifact, "utf8");
  for (const [rel, src] of Object.entries(files)) {
    const abs = path.join(root, rel);
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, src, "utf8");
  }
  return root;
}

function withFixture(files: Record<string, string>, body: (root: string) => void): void {
  const root = makeFixture(files);
  try {
    body(root);
  } finally {
    rmSync(root, { recursive: true, force: true, maxRetries: 3 });
  }
}

// ---------------------------------------------------------------------------
// The forbidden set is derived from the artifact, not hardcoded.
// ---------------------------------------------------------------------------

describe("Requirement 9.9: the forbidden set is derived from the artifact", () => {
  it("reads exactly the four fact statuses and the eight quantity kinds", () => {
    expect(forbidden.statuses).toEqual(["pending", "active", "disputed", "retired"]);
    expect(forbidden.quantityKinds).toEqual([
      "year",
      "count",
      "percentage",
      "ratio",
      "physical_measure",
      "money",
      "duration",
      "rating",
    ]);
  });

  it("forbids a status added to the artifact without any code change here", () => {
    const extended = ARTIFACT_SOURCE.replace(
      '"retired"] as const',
      '"retired", "archived"] as const',
    );
    const extendedSet = parseForbiddenLiterals(extended).values;
    expect(extendedSet.has("archived")).toBe(true);
    expect(scanSourceForLiterals('const s = "archived";', extendedSet)).toHaveLength(1);
    // …and the original set does not forbid it, proving derivation not hardcoding.
    expect(forbidden.values.has("archived")).toBe(false);
  });
});

// ---------------------------------------------------------------------------
// Property 31 — over the pure scanner
// ---------------------------------------------------------------------------

const forbiddenValueArb = fc.constantFrom(...FORBIDDEN_VALUES);
const quoteArb = fc.constantFrom('"', "'");

describe("Property 31: a forbidden value as a string literal is a hit; otherwise it is not", () => {
  it("flags a plain quoted string literal equal to any forbidden value", () => {
    fc.assert(
      fc.property(forbiddenValueArb, quoteArb, (value, quote) => {
        const source = `export const s = ${quote}${value}${quote};`;
        const hits = scanSourceForLiterals(source, forbidden.values);
        expect(hits).toHaveLength(1);
        expect(hits[0].literal).toBe(value);
      }),
      { numRuns: 200 },
    );
  });

  it("does not flag a forbidden value used as an identifier, property, or bare word", () => {
    fc.assert(
      fc.property(
        forbiddenValueArb,
        fc.constantFrom(
          (v: string) => `const ${v} = 1;`,
          (v: string) => `obj.${v};`,
          (v: string) => `function ${v}() { return 1; }`,
          (v: string) => `// a comment about ${v} statuses`,
          (v: string) => `/* block ${v} comment */`,
        ),
        (value, build) => {
          // Identifiers can't contain a `.`; skip such values for the identifier shapes.
          fc.pre(/^[A-Za-z_$][\w$]*$/.test(value));
          const hits = scanSourceForLiterals(build(value), forbidden.values);
          expect(hits).toHaveLength(0);
        },
      ),
      { numRuns: 200 },
    );
  });

  it("does not flag a longer string that merely contains a forbidden value", () => {
    fc.assert(
      fc.property(
        forbiddenValueArb,
        quoteArb,
        fc.constantFrom("in 2019", "and more", "region", "reactive", "counted"),
        (value, quote, extra) => {
          const source = `const q = ${quote}${value} ${extra}${quote};`;
          const hits = scanSourceForLiterals(source, forbidden.values);
          expect(hits).toHaveLength(0);
        },
      ),
      { numRuns: 200 },
    );
  });
});

// ---------------------------------------------------------------------------
// End-to-end over real fixture directories
// ---------------------------------------------------------------------------

describe("Requirement 9.9: the runner scans a real tree and never modifies a file", () => {
  it("exits 0 on a clean tree, writing nothing to standard error", () => {
    withFixture(
      {
        "src/clean.ts":
          'import { FACT_STATUSES } from "../shared/fact-lifecycle-contract.gen";\n' +
          "export const first = FACT_STATUSES[0];\n" +
          '// active and retired mentioned only in a comment\n',
      },
      (root) => {
        const outcome = runContractLiteralCheck(root);
        expect(outcome.ok).toBe(true);
        expect(outcome.exitCode).toBe(0);
        expect(outcome.stderr).toEqual([]);
        expect(outcome.stdout.join("\n")).toContain("OK");
      },
    );
  });

  it("exits non-zero and reports path:line: literal for each hit, sorted by path then line", () => {
    withFixture(
      {
        "src/b.ts": 'export const s = "active";\n',
        "src/a.ts": "export const x = 1;\nexport const q = 'physical_measure';\nexport const y = \"year\";\n",
      },
      (root) => {
        const outcome = runContractLiteralCheck(root);
        expect(outcome.ok).toBe(false);
        expect(outcome.exitCode).toBe(EXIT_LITERAL_FOUND);
        const err = outcome.stderr.join("\n");
        expect(err).toContain('src/a.ts:2: "physical_measure"');
        expect(err).toContain('src/a.ts:3: "year"');
        expect(err).toContain('src/b.ts:1: "active"');

        // Sorted by path then line: a.ts entries precede b.ts.
        const aIndex = err.indexOf("src/a.ts:2");
        const bIndex = err.indexOf("src/b.ts:1");
        expect(aIndex).toBeGreaterThanOrEqual(0);
        expect(bIndex).toBeGreaterThan(aIndex);
      },
    );
  });

  it("excludes the artifact itself from the scan", () => {
    // The artifact declares every forbidden literal, yet living at its own path it
    // must never be reported.
    withFixture({ "src/ok.ts": "export const n = 1;\n" }, (root) => {
      const outcome = runContractLiteralCheck(root);
      expect(outcome.ok).toBe(true);
      expect(outcome.stderr.join("\n")).not.toContain(ARTIFACT_RELATIVE_PATH);
    });
  });

  it("fails closed with a non-zero exit when the artifact is absent", () => {
    const root = mkdtempSync(path.join(os.tmpdir(), "contract-literals-noart-"));
    try {
      mkdirSync(path.join(root, "src"), { recursive: true });
      writeFileSync(path.join(root, "src/x.ts"), 'export const s = "active";\n', "utf8");
      const outcome = runContractLiteralCheck(root);
      expect(outcome.ok).toBe(false);
      expect(outcome.exitCode).toBe(EXIT_ARTIFACT_UNREADABLE);
      expect(outcome.stderr.join("\n")).toContain("absent");
    } finally {
      rmSync(root, { recursive: true, force: true, maxRetries: 3 });
    }
  });

  it("does not modify any scanned file", () => {
    withFixture({ "src/planted.ts": 'export const s = "active";\n' }, (root) => {
      const target = path.join(root, "src/planted.ts");
      const before = readFileSync(target);
      runContractLiteralCheck(root);
      const after = readFileSync(target);
      expect(after.equals(before)).toBe(true);
    });
  });
});
