/**
 * Revision-bound quality review records and the material-edit field set
 * (Requirement: Task 7 revision-safe corrections).
 *
 * Every moderation decision that accepts a flagged finding, clears findings,
 * or resolves a source interpretation is appended to the fact's
 * `quality_reviews` array inside the same transaction that mutates the fact.
 * The record binds the exact revision reviewed: the stored
 * `content_fingerprint` (stamped by Go pipeline writes) and the document
 * `update_time` read inside the transaction. Go-side lint suppression only
 * honors a review whose bound fingerprint or update time still matches the
 * current document, and whose `lint_rules_revision` matches the running
 * ruleset; a stale review can never silently suppress fresh findings.
 *
 * The closed set of record kinds is generated by the Main repository's
 * shared contract (`QUALITY_REVIEW_KINDS`), never restated here.
 */
import {
  QUALITY_REVIEW_KINDS,
  type QualityReviewKind,
} from "../../../shared/fact-lifecycle-contract.gen";
import type { FirestoreDoc } from "../firebase/firestore.server";

export { QUALITY_REVIEW_KINDS };
export type { QualityReviewKind };

export const QUALITY_REVIEW_SCHEMA = "fact-quality-review/1";

/**
 * The fact fields covered by `content_fingerprint`: a change to any of them
 * means the persisted revision no longer matches a previously issued approval
 * or review, so readiness (receipt), the stored fingerprint, and lint evidence
 * minted against the old revision must be invalidated atomically with the
 * edit. `difficulty_hint` is deliberately absent; it is not fingerprinted.
 */
export const MATERIAL_EDIT_KEYS = [
  "category",
  "sub_category",
  "question",
  "claim_template",
  "true_number",
  "unit",
  "quantity_kind",
  "explanation",
  "context",
  "source_urls",
  "plausible_min",
  "plausible_max",
  "surprise_factor",
  "content_rating",
] as const;

/**
 * Field paths deleted when a material edit lands: the approval bound to the
 * old revision, the stored fingerprint of that revision, and lint evidence
 * computed from it. `disputed_reason`/`disputed_at`/`disputedAt` and `status`
 * are NOT deleted; a material edit does not self-clear a live dispute.
 */
export const MATERIAL_INVALIDATION_PATHS = [
  "quality_receipt",
  "content_fingerprint",
  "quality_flags",
  "lint_findings",
  "lint_rules_revision",
] as const;

/**
 * Every field a moderation path clears when a flag-based dispute is resolved.
 * Includes the `disputedAt` camelCase marker older telemetry writes left on
 * fact documents, and the lint evidence so a resolved dispute leaves no
 * stale findings behind.
 */
export const DISPUTE_CLEAR_PATHS = [
  "quality_flags",
  "disputed_reason",
  "disputed_at",
  "disputedAt",
  "lint_findings",
  "lint_rules_revision",
] as const;

export interface QualityReviewRecord {
  schema_version: typeof QUALITY_REVIEW_SCHEMA;
  review_id: string;
  fact_id: string;
  kind: QualityReviewKind;
  actor: string;
  actor_role: string;
  reason: string;
  reviewed_fields: string[];
  finding_ids: string[];
  lint_rules_revision: string;
  /** Stored `content_fingerprint` of the reviewed revision; "" when absent. */
  content_fingerprint: string;
  /** Firestore `updateTime` of the reviewed revision, read inside the tx. */
  update_time: string;
  created_at: string;
}

let reviewCounter = 0;

/**
 * Build an append-only review record bound to the fact revision that was
 * read inside the current transaction. `doc` must be the same transaction
 * snapshot the mutation is applied to, so the bound update time can never
 * describe a different revision than the one reviewed.
 */
export function buildQualityReview(input: {
  factId: string;
  kind: QualityReviewKind;
  actor: string;
  reason: string;
  findingIds?: readonly string[];
  reviewedFields?: readonly string[];
  doc: FirestoreDoc;
  now?: string;
}): QualityReviewRecord {
  const fingerprint = input.doc.data["content_fingerprint"];
  const rulesRevision = input.doc.data["lint_rules_revision"];
  reviewCounter += 1;
  return {
    schema_version: QUALITY_REVIEW_SCHEMA,
    review_id: `qr_${input.factId}_${Date.now()}_${reviewCounter}_${crypto.randomUUID().replace(/-/g, "").slice(0, 8)}`,
    fact_id: input.factId,
    kind: input.kind,
    actor: input.actor,
    actor_role: "moderator",
    reason: input.reason,
    reviewed_fields: [...(input.reviewedFields ?? [])],
    finding_ids: [...(input.findingIds ?? [])],
    lint_rules_revision: typeof rulesRevision === "string" ? rulesRevision : "",
    content_fingerprint: typeof fingerprint === "string" ? fingerprint : "",
    update_time: input.doc.updateTime ?? "",
    created_at: input.now ?? new Date().toISOString(),
  };
}

/**
 * Append a review record to the document's `quality_reviews` array, preserving
 * every existing entry (malformed entries included; the array is append-only
 * and never rewritten or trimmed by moderation paths).
 */
export function appendQualityReview(
  existing: unknown,
  record: QualityReviewRecord,
): unknown[] {
  const list = Array.isArray(existing) ? [...existing] : [];
  list.push(record);
  return list;
}

/** The stored lint finding ids a fact document currently carries. */
export function currentFindingIds(data: Record<string, unknown>): string[] {
  const out: string[] = [];
  const flags = data["quality_flags"];
  if (Array.isArray(flags)) {
    for (const flag of flags) {
      if (typeof flag === "string" && flag.trim()) out.push(flag.trim());
    }
  }
  const findings = data["lint_findings"];
  if (Array.isArray(findings)) {
    for (const finding of findings) {
      if (finding && typeof finding === "object") {
        const id = (finding as Record<string, unknown>)["id"];
        if (typeof id === "string" && id.trim() && !out.includes(id.trim())) {
          out.push(id.trim());
        }
      }
    }
  }
  return out;
}

/**
 * The quality hold written when a material edit lands. It does not change
 * lifecycle status; it marks the stored approval as revoked so readiness
 * gates downstream require a fresh audit receipt.
 */
export function materialEditHold(input: {
  auditId: string;
  reason: string;
  now: string;
}): Record<string, unknown> {
  return {
    audit_id: input.auditId,
    checked_at: input.now,
    reason: input.reason,
  };
}
